/**
 * DEV-ONLY: turn an archived analysis row into the gitignored offline fixture
 * that the `offline` build configuration compiles in (see
 * src/app/offline/offline-fixture.ts).
 *
 *   node tools/make-offline-fixture.mjs <row.json> <stock.json> <refs.json>
 *
 *  row.json   — [{ id, run_at, summary, political, …, metrics, r5_synthesis, chains }]
 *               (stock_analyses_history row; chains = raw_output modules)
 *  stock.json — [stocks row]   refs.json — [{ module, refs }] citation_refs rows
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [rowPath, stockPath, refsPath] = process.argv.slice(2);
if (!rowPath || !stockPath || !refsPath) {
  console.error('usage: node tools/make-offline-fixture.mjs <row.json> <stock.json> <refs.json>');
  process.exit(2);
}
const one = (p) => { const j = JSON.parse(readFileSync(p, 'utf8')); return Array.isArray(j) ? j[0] : j; };
const row = one(rowPath);
const stock = one(stockPath);
const citationRows = JSON.parse(readFileSync(refsPath, 'utf8'));
const { chains, ...rest } = row;
const analysis = {
  id: rest.id, stock_id: stock.id, source: rest.source,
  // PostgREST shape ("…T00:00:00+00:00"); the SQL endpoint prints "… 00:00:00+00"
  run_at: new Date(String(rest.run_at).replace(' ', 'T').replace(/([+-]\d{2})$/, '$1:00')).toISOString().replace('.000Z', '+00:00'),
  summary: rest.summary, political: rest.political, price: rest.price, macro: rest.macro,
  management: rest.management, sentiment: rest.sentiment, competitor: rest.competitor,
  financial: rest.financial, metrics: rest.metrics, r5_synthesis: rest.r5_synthesis ?? null,
};
const out = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src/app/offline/offline-fixture.local.ts');
writeFileSync(out,
  `// GENERATED by tools/make-offline-fixture.mjs — dev-only, gitignored. Do not commit.\n` +
  `import { OfflineFixture } from './offline-fixture';\n\n` +
  `export const OFFLINE_FIXTURE: OfflineFixture | null = ${JSON.stringify({ stock, analysis, chains, citationRows })};\n`);
console.log(`wrote ${out} (${stock.ticker} ${analysis.run_at}, ${citationRows.length} citation rows)`);
